-- Move timing values already present in skill raw_data into first-class columns.
update public.operator_skills
set
    duration_seconds = coalesce(
        duration_seconds,
        nullif(raw_data ->> 'actionDurationSeconds', '')::numeric,
        nullif(raw_data ->> 'castDurationSeconds', '')::numeric
    ),
    hit_timings = case
        when cardinality(hit_timings) > 0 then hit_timings
        when jsonb_typeof(raw_data -> 'hitTimings') = 'array' then array(
            select value::numeric from jsonb_array_elements_text(raw_data -> 'hitTimings')
        )
        else '{}'::numeric[]
    end,
    hit_timing_mode = coalesce(nullif(raw_data ->> 'hitTimingMode', ''), hit_timing_mode, 'absolute'),
    effect_timings = case
        when cardinality(effect_timings) > 0 then effect_timings
        when jsonb_typeof(raw_data -> 'effectTimings') = 'array' then array(
            select value::numeric from jsonb_array_elements_text(raw_data -> 'effectTimings')
        )
        when (raw_data #>> '{delayedFollowUp,delaySeconds}') ~ '^[0-9]+(\.[0-9]+)?$'
            then array[(raw_data #>> '{delayedFollowUp,delaySeconds}')::numeric]
        when (raw_data #>> '{manualSequence,automaticDelaySeconds}') ~ '^[0-9]+(\.[0-9]+)?$'
            then array[(raw_data #>> '{manualSequence,automaticDelaySeconds}')::numeric]
        else '{}'::numeric[]
    end,
    form_key = coalesce(nullif(raw_data ->> 'formKey', ''), form_key, 'base'),
    variant_key = coalesce(nullif(raw_data ->> 'variantKey', ''), variant_key, 'base');

