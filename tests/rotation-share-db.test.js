import assert from "node:assert/strict";
import fs from "node:fs";
import test from "node:test";
import { randomUUID } from "node:crypto";
import { pathToFileURL } from "node:url";

test("published shares enforce ownership, revision checks and per-browser engagement", { skip: !process.env.PGLITE_TEST_MODULE }, async () => {
    const { PGlite } = await import(pathToFileURL(process.env.PGLITE_TEST_MODULE).href);
    const db = new PGlite();
    const owner = randomUUID(), stranger = randomUUID(), browser = randomUUID(), secondBrowser = randomUUID();
    try {
        await db.exec(`
            create role anon; create role authenticated;
            create schema auth;
            create table auth.users(id uuid primary key);
            create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('test.user_id', true), '')::uuid $$;
            create function auth.jwt() returns jsonb language sql as $$ select '{}'::jsonb $$;
            grant usage on schema auth to anon, authenticated;
            grant execute on function auth.uid(), auth.jwt() to anon, authenticated;
            create table public.user_profiles(user_id uuid, username text);
            create table public.operators(id integer primary key, game text);
            insert into public.operators values (1, 'arknights_endfield'), (2, 'other');
            insert into auth.users values ('${owner}'), ('${stranger}');
            insert into public.user_profiles values ('${owner}', 'Author');
        `);
        await db.exec(fs.readFileSync("supabase/rotation_share_codes.sql", "utf8"));
        const migration = fs.readFileSync("supabase/rotation_share_editing_engagement.sql", "utf8");
        await db.exec(migration);
        await db.exec(migration); // Rerunning must retain existing data and grants.
        const call = async (name, params = []) => (await db.query(`select public.${name}(${params.map((_, i) => `$${i + 1}`).join(",")}) as result`, params)).rows[0].result;
        const signIn = id => db.exec(`set role authenticated; set test.user_id = '${id}'`);
        await signIn(owner);
        const share = await call("create_rotation_share", ["rotation", "abcdefgh", 13, [1], "My opener", "Original"]);
        assert.equal(share.can_edit, true);
        assert.equal(share.revision, 1);
        const code = share.short_code;
        const update = (revision = 1, title = "Updated opener", payload = "ijklmnop", ids = [1], type = "rotation") => call("update_rotation_share", [code, revision, type, payload, 13, ids, title, "Updated notes"]);
        await db.exec("set role anon; set test.user_id = ''");
        assert.equal((await call("resolve_rotation_share", [code])).can_edit, false);
        await assert.rejects(update(), { code: "42501" });
        await assert.rejects(call("list_my_rotation_shares", [500]), { code: "42501" });
        await assert.rejects(db.query("select * from public.rotation_share_codes"), { code: "42501" });
        await assert.rejects(db.query("select * from public.rotation_share_engagement"), { code: "42501" });
        assert.equal((await call("get_rotation_share_engagement", [[code], browser]))[code].view_count, 0);
        await call("record_rotation_share_view", [code, browser]);
        assert.equal((await call("record_rotation_share_view", [code, browser])).view_count, 1);
        assert.equal((await call("record_rotation_share_view", [code, secondBrowser])).view_count, 2);
        let stats = await call("set_rotation_share_reaction", [code, browser, "like"]);
        assert.equal(stats.like_count, 1);
        assert.equal(stats.reaction, "like");
        stats = await call("set_rotation_share_reaction", [code, browser, "dislike"]);
        assert.equal(stats.like_count, 0);
        assert.equal(stats.dislike_count, 1);
        stats = await call("set_rotation_share_reaction", [code, browser, null]);
        assert.equal(stats.dislike_count, 0);
        await call("set_rotation_share_reaction", [code, browser, "like"]);
        await assert.rejects(call("set_rotation_share_reaction", [code, browser, "invalid"]), { code: "22023" });
        await assert.rejects(call("record_rotation_share_view", [code, null]), { code: "22023" });
        await signIn(stranger);
        await assert.rejects(update(), { code: "42501" });
        assert.equal((await call("list_my_rotation_shares", [500])).items.length, 0);
        assert.equal((await call("list_public_rotation_shares", [500])).items[0].can_edit, false);
        await signIn(owner);
        assert.equal((await call("list_my_rotation_shares", [500])).items[0].can_edit, true);
        await assert.rejects(update(1, "x"), { code: "22023" });
        await assert.rejects(update(1, "Valid title", "bad!payload"), { code: "22023" });
        await assert.rejects(update(1, "Valid title", "abcdefgh", [2]), { code: "22023" });
        await assert.rejects(update(1, "Valid title", "abcdefgh", [1], "simulation"), { code: "22023" });
        const updated = await update();
        assert.equal(updated.short_code, code);
        assert.equal(updated.revision, 2);
        assert.equal(updated.created_at, share.created_at);
        assert.equal(updated.share_payload, "ijklmnop");
        assert.equal(updated.title, "Updated opener");
        assert.equal(updated.author_name, "Author");
        assert.ok(updated.updated_at);
        await assert.rejects(update(), { code: "40001" });
        stats = (await call("get_rotation_share_engagement", [[code], browser]))[code];
        assert.equal(stats.view_count, 2);
        assert.equal(stats.like_count, 1);
        assert.equal((await call("list_public_rotation_shares", [500])).rotation_count, 1);
        // Anonymous publications cannot be claimed later, even by an administrator account.
        await db.exec("set role anon; set test.user_id = ''");
        const anonymous = await call("create_rotation_share", ["rotation", "anonymous123", 13, [1], "Anonymous opener", ""]);
        await signIn(owner);
        await assert.rejects(call("update_rotation_share", [anonymous.short_code, 1, "rotation", "abcdefgh", 13, [1], "Claimed title", ""]), { code: "42501" });
        await db.exec(`reset role; update public.rotation_share_codes set is_public = false where short_code = '${code}'`);
        await db.exec("set role anon; set test.user_id = ''");
        assert.deepEqual(await call("get_rotation_share_engagement", [[code], browser]), {});
        await assert.rejects(call("record_rotation_share_view", [code, browser]), { code: "P0002" });
        await assert.rejects(call("set_rotation_share_reaction", [code, browser, "like"]), { code: "P0002" });
    } finally { await db.close(); }
});
