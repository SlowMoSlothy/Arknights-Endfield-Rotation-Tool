import fs from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { argentFlowSkills, argentFlowForm, argentFlowFormVariant, ARGENT_FLOW_SOURCE, ARGENT_FLOW_LIMITATIONS } from './data/argent-flow-rotation-profile.js';

const literal = value => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
const insertRows = (table, rows) => {
  const fields = Object.keys(rows[0]).join(',');
  return `insert into public.${table} (${fields})\nselect ${fields} from jsonb_populate_recordset(null::public.${table}, ${literal(rows)});`;
};

export function buildArgentFlowSkillsSql() {
  const rows = argentFlowSkills.map((skill, index) => ({
    id: skill.id, operator_id: 34, slot_index: index + 1,
    name: skill.name, skill_type: skill.type, short_type: skill.shortType,
    cooldown: skill.cooldown, energy: skill.energy, element_type: skill.elementType,
    icon_path: skill.icon, icon_small_path: skill.iconSmall, description: skill.description,
    combo_trigger_mode: skill.comboTriggerMode || null,
    atk_multiplier: skill.damageProfile.atkMultiplier, flat_damage: 0, hit_count: 1,
    damage_element: skill.damageProfile.element, damage_verified: true, damage_source_url: ARGENT_FLOW_SOURCE,
    raw_data: skill
  }));
  return `-- Generated by node tools/build-argent-flow-skills.js. Rank 12; see tools/data/argent-flow-rotation-profile.js.
begin;
set local standard_conforming_strings=on;
lock table public.operators, public.operator_skills, public.operator_forms, public.operator_form_action_variants in share row exclusive mode;
do $guard$
begin
  if not exists(select 1 from public.operators where id=34 and slug='argent_flow' and game='arknights_endfield') then
    raise exception 'Argent Flow operator identity is missing or changed';
  end if;
  if exists(select 1 from public.operator_skills where operator_id=34 or id in (${rows.map(row => row.id).join(',')})) then
    raise exception 'Argent Flow skills already exist or a skill ID is occupied; review before applying';
  end if;
  if exists(select 1 from public.operator_forms where operator_id=34) or exists(select 1 from public.operator_form_action_variants where operator_id=34) then
    raise exception 'Argent Flow form mechanics already exist; review before applying';
  end if;
end $guard$;
${insertRows('operator_skills', rows)}
${insertRows('operator_forms', [argentFlowForm])}
${insertRows('operator_form_action_variants', [argentFlowFormVariant])}
update public.operators set raw_data=coalesce(raw_data,'{}'::jsonb) || ${literal({ dataStatus: 'rotation_profile', sourceNote: ARGENT_FLOW_LIMITATIONS })}, updated_at=now() where id=34;
commit;
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await fs.writeFile('supabase/argent_flow_skill_update.sql', buildArgentFlowSkillsSql());
  console.log('Generated supabase/argent_flow_skill_update.sql (6 Argent Flow skills and Bolt Rush form).');
}
