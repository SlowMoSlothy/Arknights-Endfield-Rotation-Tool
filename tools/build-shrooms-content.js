import fs from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { kaySkills, miminoSkills, kayResources, miminoResources, KAY_LIMITATIONS, MIMINO_LIMITATIONS } from './data/shrooms-rotation-profiles.js';
import { validateOperators, createSupabaseClient, fetchSkillsForOperators, fetchBasicAttackSequences, groupBasicAttackSequences, writeGeneratedOutput } from './build-operator-pages.js';
import { validateWeapons, fetchWeapons, writeWeaponOutput } from './build-weapon-pages.js';
import { publicConfiguration, requestJson } from './sync-endfield-equipment.js';

export const snapshotUrl = new URL('./data/shrooms-content-snapshot.json', import.meta.url);
export async function shroomsContent() {
  const data = JSON.parse(await fs.readFile(snapshotUrl, 'utf8'));
  if (data.version !== 1 || data.releaseDate !== '2026-11-25') throw new Error('Unexpected content snapshot');
  validateOperators(data.operators);
  validateWeapons(data.weapons);
  for (const row of [...data.operators, ...data.weapons]) {
    row.created_at = '2026-11-25T00:00:00Z';
    row.updated_at = row.created_at;
  }
  const profiles = [[35, kaySkills, kayResources, KAY_LIMITATIONS], [36, miminoSkills, miminoResources, MIMINO_LIMITATIONS]];
  for (const [id, , resources, limitations] of profiles) {
    const operator = data.operators.find(row => row.id === id);
    if (!operator || operator.slug !== (id === 35 ? 'kay' : 'mimino')) throw new Error('Operator identity changed');
    operator.raw_data = { ...operator.raw_data, comboResources: resources, sourceNote: limitations,
      dataStatus: id === 35 ? 'rotation_profile' : 'announced_preview' };
  }
  data.skills = profiles.flatMap(([operatorId, skills]) => skills.map((skill, index) => ({
    id: skill.id, operator_id: operatorId, slot_index: index + 1,
    name: skill.name, skill_type: skill.type, short_type: skill.shortType,
    cooldown: skill.cooldown, energy: skill.energy, element_type: skill.elementType,
    icon_path: skill.icon, icon_small_path: skill.iconSmall, description: skill.description || '',
    atk_multiplier: skill.damageProfile?.atkMultiplier ?? null,
    flat_damage: 0, hit_count: 1,
    damage_element: skill.elementType, damage_verified: skill.damageProfile?.verified === true,
    damage_source_url: skill.damageProfile?.sourceUrl || '', raw_data: skill
  })));
  if (data.skills.length !== 10 || new Set(data.skills.map(row => row.id)).size !== 10) throw new Error('Invalid skills');
  return data;
}

const literal = value => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
function insert(table, rows) {
  const columns = [...new Set(rows.flatMap(Object.keys))].join(',');
  return `insert into public.${table} (${columns}) select ${columns} from jsonb_populate_recordset(null::public.${table}, ${literal(rows)});`;
}
export async function buildShroomsContentSql() {
  const data = await shroomsContent();
  return [
    '-- Generated by node tools/build-shrooms-content.js. Version 1.7, 2026-11-25.',
    '-- Kay: rank 12. Mimino/Star of Tomorrow: announced previews with unknown values retained as NULL.',
    'begin;', 'set local standard_conforming_strings=on;',
    'lock table public.operators, public.operator_skills, public.weapons, public.weapon_essence_profiles in share row exclusive mode;',
    'do $guard$ begin',
    "if exists(select 1 from public.operators where id in (35,36) or slug in ('kay','mimino')) then raise exception 'Kay/Mimino identity occupied; compare the database before applying'; end if;",
    `if exists(select 1 from public.operator_skills where operator_id in (35,36) or id in (${data.skills.map(row => row.id).join(',')})) then raise exception 'Skill identity occupied; no existing skills were changed'; end if;`,
    "if exists(select 1 from public.weapons where weapon_key in ('sweet_deal','raid_comet','star_of_tomorrow')) or exists(select 1 from public.weapon_essence_profiles where weapon_key in ('sweet_deal','raid_comet','star_of_tomorrow')) then raise exception 'Weapon identity occupied; compare the database before applying'; end if;",
    'end $guard$;',
    insert('operators', data.operators), insert('operator_skills', data.skills),
    insert('weapons', data.weapons), insert('weapon_essence_profiles', data.profiles),
    'commit;', ''
  ].join('\n');
}

// Regenerate with the established catalog builders. The public database remains
// authoritative; these additions are overlaid only until the SQL is installed.
export async function buildShroomsPages() {
  const data = await shroomsContent(), config = await publicConfiguration(process.env);
  const client = createSupabaseClient({ SUPABASE_URL: config.url, SUPABASE_ANON_KEY: config.key });
  const existing = await requestJson(`${config.url}/rest/v1/operators?select=*&game=eq.arknights_endfield&order=sort_order`, { headers: { apikey: config.key } });
  const operatorById = new Map(existing.map(row => [row.id, row]));
  for (const row of data.operators) {
    if ([...operatorById.values()].some(old => (old.id === row.id || old.slug === row.slug) && (old.id !== row.id || old.slug !== row.slug))) throw new Error('Operator overlay identity collision');
    if (!operatorById.has(row.id)) operatorById.set(row.id, row);
  }
  const operators = [...operatorById.values()].filter(row => row.is_visible !== false);
  const ids = existing.map(row => row.id);
  const [skills, sequences, weaponRows] = await Promise.all([
    fetchSkillsForOperators(client, ids), fetchBasicAttackSequences(client, ids), fetchWeapons(client)
  ]);
  const skillsByOperator = new Map();
  for (const row of [...skills, ...data.skills.filter(row => !skills.some(old => old.operator_id === row.operator_id))]) {
    if (!skillsByOperator.has(row.operator_id)) skillsByOperator.set(row.operator_id, []);
    skillsByOperator.get(row.operator_id).push(row);
  }
  const { baseByOperator, formsByOperator } = groupBasicAttackSequences(sequences);
  for (const row of operators) {
    if (!row.raw_data?.basicAttack && !row.raw_data?.basic_attack) row.basicAttack = baseByOperator.get(row.id);
  }
  writeGeneratedOutput({ operators, skillsByOperator, basicAttackFormsByOperator: formsByOperator });
  const weaponsByKey = new Map(weaponRows.map(row => [row.weapon_key, row]));
  for (const row of data.weapons) if (!weaponsByKey.has(row.weapon_key)) weaponsByKey.set(row.weapon_key, {
    ...row, profile: data.profiles.find(profile => profile.weapon_key === row.weapon_key) || null
  });
  writeWeaponOutput([...weaponsByKey.values()]);
  return { operators: operators.length, weapons: weaponsByKey.size };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await fs.writeFile(new URL('../supabase/content_update_2026_11_25.sql', import.meta.url), await buildShroomsContentSql());
  console.log('Generated supabase/content_update_2026_11_25.sql; no database writes.');
  if (process.argv.includes('--pages')) console.log(await buildShroomsPages());
}
